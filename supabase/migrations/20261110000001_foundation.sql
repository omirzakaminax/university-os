-- University OS — migration 1: foundation
-- Profiles, preferences, institution & grading configuration, academic calendar,
-- notifications and audit log. All tables are private to their owner via RLS.
--
-- Ownership model
--   * Every private table has `user_id uuid not null default auth.uid() references auth.users`.
--   * Parent/child relations between private tables use COMPOSITE foreign keys
--     (child_fk, user_id) -> parent(id, user_id). Foreign-key checks bypass RLS, so a plain
--     FK would let a user attach their rows to another user's parent row if they ever learned
--     its UUID. The composite key makes that structurally impossible.
--   * RLS policies are generated by private.enable_owner_rls() so no table can be forgotten;
--     tests/db/rls.test.ts additionally asserts every user-owned table is covered.

create schema if not exists private;
revoke all on schema private from public;

create or replace function private.set_updated_at() returns trigger
language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end $$;

-- Enables RLS and creates owner-only select/insert/update/delete policies.
-- `delete_allowed = false` produces an append-only table for end users.
create or replace function private.enable_owner_rls(tbl regclass, delete_allowed boolean default true,
                                                    update_allowed boolean default true)
returns void language plpgsql as $$
declare
  t text := (select relname from pg_class where oid = tbl);
begin
  execute format('alter table %s enable row level security', tbl);
  execute format('grant select, insert on %s to authenticated', tbl);
  execute format('create policy %I on %s for select to authenticated using (user_id = (select auth.uid()))',
                 t || '_select_own', tbl);
  execute format('create policy %I on %s for insert to authenticated with check (user_id = (select auth.uid()))',
                 t || '_insert_own', tbl);
  if update_allowed then
    execute format('grant update on %s to authenticated', tbl);
    execute format('create policy %I on %s for update to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()))',
                   t || '_update_own', tbl);
  end if;
  if delete_allowed then
    execute format('grant delete on %s to authenticated', tbl);
    execute format('create policy %I on %s for delete to authenticated using (user_id = (select auth.uid()))',
                   t || '_delete_own', tbl);
  end if;
end $$;

-- ---------------------------------------------------------------------------
-- Profiles & preferences (1:1 with auth.users, created by trigger)
-- ---------------------------------------------------------------------------
create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '' check (char_length(display_name) <= 100),
  timezone text not null default 'UTC' check (char_length(timezone) between 1 and 64),
  locale text not null default 'en' check (char_length(locale) between 2 and 16),
  onboarding_completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create trigger profiles_updated_at before update on public.profiles
  for each row execute function private.set_updated_at();

create table public.user_preferences (
  user_id uuid primary key references auth.users(id) on delete cascade,
  sidebar_collapsed boolean not null default false,
  week_starts_on smallint not null default 1 check (week_starts_on between 0 and 6),
  -- Ordered list of {id, visible}; normalised against the widget registry in application code.
  dashboard_widgets jsonb not null default '[]'::jsonb check (jsonb_typeof(dashboard_widgets) = 'array'),
  notification_preferences jsonb not null default '{}'::jsonb check (jsonb_typeof(notification_preferences) = 'object'),
  active_period_id uuid,
  updated_at timestamptz not null default now()
);
create trigger user_preferences_updated_at before update on public.user_preferences
  for each row execute function private.set_updated_at();

-- A new auth user always starts with an empty, independent workspace.
create or replace function private.handle_new_user() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, display_name)
  values (new.id, left(coalesce(nullif(new.raw_user_meta_data ->> 'display_name', ''), split_part(coalesce(new.email, ''), '@', 1)), 100));
  insert into public.user_preferences (user_id) values (new.id);
  return new;
end $$;

create trigger on_auth_user_created after insert on auth.users
  for each row execute function private.handle_new_user();

alter table public.profiles enable row level security;
grant select, update on public.profiles to authenticated;
create policy profiles_select_own on public.profiles for select to authenticated using (id = (select auth.uid()));
create policy profiles_update_own on public.profiles for update to authenticated
  using (id = (select auth.uid())) with check (id = (select auth.uid()));

alter table public.user_preferences enable row level security;
grant select, update on public.user_preferences to authenticated;
create policy user_preferences_select_own on public.user_preferences for select to authenticated using (user_id = (select auth.uid()));
create policy user_preferences_update_own on public.user_preferences for update to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));

-- ---------------------------------------------------------------------------
-- Institution, grading scale, programme, academic years & periods
-- ---------------------------------------------------------------------------
create table public.institutions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name text not null check (char_length(name) between 1 and 200),
  short_name text check (char_length(short_name) <= 30),
  country text check (country ~ '^[A-Z]{2}$'),
  timezone text not null check (char_length(timezone) between 1 and 64),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (id, user_id)
);
create index institutions_user_idx on public.institutions(user_id);
create trigger institutions_updated_at before update on public.institutions
  for each row execute function private.set_updated_at();

create table public.grading_scales (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  institution_id uuid,
  name text not null check (char_length(name) between 1 and 120),
  description text check (char_length(description) <= 500),
  -- How a percentage is rounded before band lookup.
  rounding text not null default 'none' check (rounding in ('none', 'half_up')),
  max_points numeric(4,2) not null default 4.0 check (max_points > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (id, user_id),
  foreign key (institution_id, user_id) references public.institutions(id, user_id) on delete set null (institution_id)
);
create index grading_scales_user_idx on public.grading_scales(user_id);
create trigger grading_scales_updated_at before update on public.grading_scales
  for each row execute function private.set_updated_at();

create table public.grading_scale_bands (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  scale_id uuid not null,
  letter text not null check (char_length(letter) between 1 and 6),
  min_percent numeric(5,2) not null check (min_percent between 0 and 100),
  points numeric(4,2) not null check (points >= 0),
  unique (scale_id, min_percent),
  unique (scale_id, letter),
  foreign key (scale_id, user_id) references public.grading_scales(id, user_id) on delete cascade
);
create index grading_scale_bands_scale_idx on public.grading_scale_bands(scale_id);

create table public.academic_programs (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  institution_id uuid not null,
  grading_scale_id uuid,
  name text not null check (char_length(name) between 1 and 200),
  degree_level text not null default 'bachelor' check (degree_level in ('certificate', 'diploma', 'bachelor', 'master', 'doctorate', 'other')),
  major text check (char_length(major) <= 200),
  period_system text not null default 'semester' check (period_system in ('trimester', 'semester', 'quarter', 'custom')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (id, user_id),
  foreign key (institution_id, user_id) references public.institutions(id, user_id) on delete cascade,
  foreign key (grading_scale_id, user_id) references public.grading_scales(id, user_id) on delete set null (grading_scale_id)
);
create index academic_programs_user_idx on public.academic_programs(user_id);
create trigger academic_programs_updated_at before update on public.academic_programs
  for each row execute function private.set_updated_at();

create table public.academic_years (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  program_id uuid not null,
  label text not null check (char_length(label) between 1 and 60),
  starts_on date not null,
  ends_on date not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (ends_on > starts_on),
  unique (id, user_id),
  unique (program_id, label),
  foreign key (program_id, user_id) references public.academic_programs(id, user_id) on delete cascade
);
create index academic_years_user_idx on public.academic_years(user_id, starts_on desc);
create trigger academic_years_updated_at before update on public.academic_years
  for each row execute function private.set_updated_at();

create table public.academic_periods (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  academic_year_id uuid not null,
  name text not null check (char_length(name) between 1 and 80),
  kind text not null default 'semester' check (kind in ('trimester', 'semester', 'quarter', 'custom')),
  position smallint not null default 1 check (position >= 1),
  starts_on date not null,
  ends_on date not null,
  archived_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (ends_on > starts_on),
  unique (id, user_id),
  unique (academic_year_id, name),
  foreign key (academic_year_id, user_id) references public.academic_years(id, user_id) on delete cascade
);
create index academic_periods_user_idx on public.academic_periods(user_id, starts_on desc);
create trigger academic_periods_updated_at before update on public.academic_periods
  for each row execute function private.set_updated_at();

alter table public.user_preferences
  add constraint user_preferences_active_period_fk
  foreign key (active_period_id, user_id) references public.academic_periods(id, user_id)
  on delete set null (active_period_id);

select private.enable_owner_rls('public.institutions');
select private.enable_owner_rls('public.grading_scales');
select private.enable_owner_rls('public.grading_scale_bands');
select private.enable_owner_rls('public.academic_programs');
select private.enable_owner_rls('public.academic_years');
select private.enable_owner_rls('public.academic_periods');

-- ---------------------------------------------------------------------------
-- Notifications (in-app) and audit log
-- ---------------------------------------------------------------------------
create table public.notifications (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  category text not null check (category in ('deadline', 'reminder', 'overdue', 'academic', 'system')),
  title text not null check (char_length(title) between 1 and 200),
  body text check (char_length(body) <= 1000),
  -- Internal deep link only (never an external URL).
  href text check (href ~ '^/[^/\\]'),
  -- Idempotency key so periodic generation never duplicates a notification.
  dedupe_key text,
  read_at timestamptz,
  archived_at timestamptz,
  snoozed_until timestamptz,
  created_at timestamptz not null default now(),
  unique (user_id, dedupe_key)
);
create index notifications_inbox_idx on public.notifications(user_id, created_at desc) where archived_at is null;

create table public.audit_logs (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  action text not null check (char_length(action) between 1 and 80),
  entity_type text check (char_length(entity_type) <= 60),
  entity_id uuid,
  metadata jsonb not null default '{}'::jsonb check (jsonb_typeof(metadata) = 'object'),
  created_at timestamptz not null default now()
);
create index audit_logs_user_idx on public.audit_logs(user_id, created_at desc);

select private.enable_owner_rls('public.notifications');
-- Append-only for end users: no update, no delete.
select private.enable_owner_rls('public.audit_logs', delete_allowed => false, update_allowed => false);

-- Least privilege: nothing is exposed to unauthenticated clients.
revoke all on all tables in schema public from anon;
revoke all on all functions in schema public from anon;
alter default privileges in schema public revoke all on tables from anon;
